/**
 * UI text for a page locale; languages without a UI translation use English, then Turkish.
 * Count-dependent text picks its plural form for `vars.n` by the rules of the language the
 * text is written in.
 */
export function t(locale: string, key: MessageKey, vars?: Record<string, string | number>): string {
  for (const ui of uiLocales(locale)) {
    const text = messages[ui][key];
    if (!text) continue;
    if (typeof text === "string") return interpolate(text, vars);
    const form = text[new Intl.PluralRules(ui).select(Number(vars?.n ?? 0))] ?? text.other;
    return interpolate(form, vars);
  }
  return key;
}

/** `<html lang dir>` for a page locale, from the platform locale registry. */
export function htmlAttributes(locale: string): { lang: string; dir: TextDirection } {
  return { lang: localeInfo(locale)?.htmlLang ?? locale, dir: localeDir(locale) };
}

/** Open Graph locale (language_TERRITORY) for a page locale. */
export function ogLocale(locale: string): string {
  return localeInfo(locale)?.ogLocale ?? locale;
}

/** Name of a language in that language, for language switchers. */
export function localeName(locale: string): string {
  return localeInfo(locale)?.name ?? locale.toUpperCase();
}
