/** Push events altyapi sends to peers (§10): at most 5 attempts with exponential backoff. */
export const ekosistemDeliveries = pgTable(
  "ekosistem_deliveries",
  {
    id: uuid().primaryKey(),
    organizationId: uuid().notNull(),
    storeId: uuid().notNull(),
    linkId: uuid()
      .notNull()
      .references(() => ekosistemLinks.id, { onDelete: "cascade" }),
    /** The push `id` sent to the peer. */
    eventId: uuid().notNull(),
    type: text().notNull(),
    ref: text().notNull(),
    occurredAt: tstz().notNull(),
    status: ekosistemDeliveryStatus().notNull().default("pending"),
    attempts: integer().notNull().default(0),
    nextAttemptAt: tstz().notNull().defaultNow(),
    /**
     * Set when a sender leases the row. A row that was never leased is still collecting
     * changes: further events for the same (link, type, ref) ride along with it (30 s).
     */
    leasedUntil: tstz(),
    lastError: text(),
    deliveredAt: tstz(),
    ...timestamps,
  },
  (t) => [
    uniqueIndex("ekosistem_deliveries_uq").on(t.linkId, t.eventId),
    index("ekosistem_deliveries_due_idx").on(t.nextAttemptAt).where(sql`${t.status} = 'pending'`),
    // Coalescing (§10): at most one not-yet-sent push per (link, type, ref).
    uniqueIndex("ekosistem_deliveries_coalesce_uq")
      .on(t.linkId, t.type, t.ref)
      .where(sql`${t.status} = 'pending' and ${t.attempts} = 0 and ${t.leasedUntil} is null`),
    index("ekosistem_deliveries_finished_idx").on(t.updatedAt).where(sql`${t.status} <> 'pending'`),
  ],
);

