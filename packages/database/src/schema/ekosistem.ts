/**
 * Ekosistem v1 bridge (docs/ekosistem/v1.md): per-store links to Kârmatik and Yanıt,
 * one-time link codes, push bookkeeping, tombstones for incremental endpoints, the brand
 * profile altyapi serves, and local read models of what altyapi pulls from its peers.
 * Link secrets are envelope-encrypted and never readable through the API.
 */

export const ekosistemPeerProduct = pgEnum("ekosistem_peer_product", ["karmatik", "yanit"]);
export const ekosistemLinkRole = pgEnum("ekosistem_link_role", ["issuer", "acceptor"]);
export const ekosistemLinkStatus = pgEnum("ekosistem_link_status", ["pending", "awaiting_approval", "active", "revoked"]);
export const ekosistemDeliveryStatus = pgEnum("ekosistem_delivery_status", ["pending", "delivered", "failed"]);
export const ekosistemTombstoneResource = pgEnum("ekosistem_tombstone_resource", ["product", "order", "content"]);

/** Verified identity of the other side as it was shown to the approving user (§4.3). */
export interface EkosistemPeerAccount {
  id: string;
  label: string;
  verifiedDomain: string | null;
  ownerEmailMasked: string | null;
}

/** Retry state of the DELETE {peer}/links/{linkId} notification after a local revoke (§4.4). */
export interface EkosistemRevokeDelivery {
  attempts: number;
  nextAttemptAt: string | null;
  lastError: string | null;
  deliveredAt: string | null;
  /** Retrying stops after 72 hours. */
  giveUpAt: string;
}

export const ekosistemLinks = pgTable(
  "ekosistem_links",
  {
    /** The contract's linkId: generated by altyapi when it issued the code, else by the issuer. */
    id: uuid().primaryKey(),
    organizationId: uuid().notNull(),
    storeId: uuid()
      .notNull()
      .references(() => stores.id, { onDelete: "cascade" }),
    peerProduct: ekosistemPeerProduct().notNull(),
    /** issuer: altyapi generated the code; acceptor: the user entered a peer's code. */
    role: ekosistemLinkRole().notNull(),
    status: ekosistemLinkStatus().notNull().default("pending"),
    /** Current shared secret (43 base64url characters), envelope-encrypted. */
    secret: jsonb().$type<EncryptedEnvelope>().notNull(),
    /** Secret before the last rotation, accepted until previousSecretValidUntil (24 h). */
    previousSecret: jsonb().$type<EncryptedEnvelope>(),
    previousSecretValidUntil: tstz(),
    /** SHA-256 of the nonce of the last rotate call, so a repeated call returns the same secret. */
    rotateNonceHash: text(),
    rotatedAt: tstz(),
    /** What the peer may read from altyapi. */
    grantedScopes: text().array().notNull().default(sql`ARRAY[]::text[]`),
    /** What altyapi may read from the peer. */
    peerScopes: text().array().notNull().default(sql`ARRAY[]::text[]`),
    peerAccount: jsonb().$type<EkosistemPeerAccount>().notNull(),
    /** SHA-256 of the claimNonce; a repeated claim with the same nonce gets the same answer. */
    claimNonceHash: text(),
    /** pending / awaiting_approval links are removed after this instant (10 minutes). */
    pendingExpiresAt: tstz(),
    createdByUserId: uuid(),
    approvedByUserId: uuid(),
    approvedAt: tstz(),
    revokedAt: tstz(),
    /** user, revoked_by_peer, store_deleted, peer_unverified, ... */
    revokeReason: text(),
    revokeDelivery: jsonb().$type<EkosistemRevokeDelivery>(),
    /** Per-endpoint pull state, e.g. { "profit/variants": { since, cursor } }. */
    cursors: jsonb().$type<Record<string, unknown>>().notNull().default({}),
    lastPullAt: tstz(),
    /**
     * When the scheduled puller should look at this link again (each resource at most
     * hourly); null = due now. The scheduler leases due links by moving this forward.
     */
    nextPullAt: tstz(),
    lastError: text(),
    /** link_invalid answers in a row, counted at least 10 minutes apart (§4.4). */
    consecutiveLinkInvalid: integer().notNull().default(0),
    lastLinkInvalidAt: tstz(),
    ...timestamps,
  },
  (t) => [
    uniqueIndex("ekosistem_links_store_peer_uq").on(t.storeId, t.peerProduct).where(sql`${t.status} <> 'revoked'`),
    index("ekosistem_links_pending_idx").on(t.pendingExpiresAt).where(sql`${t.status} in ('pending', 'awaiting_approval')`),
    index("ekosistem_links_active_idx").on(t.status, t.lastPullAt),
    index("ekosistem_links_due_idx").on(t.nextPullAt).where(sql`${t.status} = 'active'`),
    index("ekosistem_links_store_idx").on(t.storeId, t.createdAt),
  ],
);

